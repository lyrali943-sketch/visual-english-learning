// Helper functions
export function getTopicsByCategory(categoryId: string): Topic[] {
  return TOPICS.filter(t => t.category === categoryId);
}

export function getTopicsByType(type: QuestionTypeId): Topic[] {
  return TOPICS.filter(t => t.questionType === type);
}

export function getTopicsByDifficulty(difficulty: Difficulty): Topic[] {
  return TOPICS.filter(t => t.difficulty === difficulty);
}

export function getTopicById(id: string): Topic | undefined {
  return TOPICS.find(t => t.id === id);
}

export function searchTopics(query: string): Topic[] {
  const lower = query.toLowerCase();
  return TOPICS.filter(t =>
    t.question.toLowerCase().includes(lower) ||
    t.tags.some(tag => tag.toLowerCase().includes(lower))
  );
}
