import { useState, useEffect, useRef, useCallback } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import {
  ArrowLeft, Play, Pause, Square, Mic, MicOff, RotateCcw,
  BookOpen, Heart, AlertCircle, Check, SkipForward,
  Sparkles, AlertTriangle, Loader2, FlaskConical, Languages,
  Lightbulb, ChevronDown,
} from 'lucide-react';
import type { Topic } from '../data/topics';
import { CATEGORIES } from '../data/categories';
import { RecorderService, type RecordingResult } from '../services/recorder';
import { formatTime } from '../utils/random';
import { savePracticeRecord, isFavorite, toggleFavorite } from '../services/storage';
import { sounds } from '../services/audio';
import AnswerFrameworkView from '../features/answer-framework/AnswerFrameworkView';
import { getSpeakingPlan, peekSpeakingPlan, type AnswerResult } from '../services/answerGenerator';
import '../styles/speaking.css';

/**
 * Compact, read-only rendering of the coach plan for the Review phase.
 * Uses the same service (and therefore the same cache) as the full panel, so
 * opening one never triggers a second request for the same question.
 */
function CoachSummary({ topic }: { topic: Topic }) {
  const [result, setResult] = useState<AnswerResult | null>(() => peekSpeakingPlan(topic) ?? null)
  const [loading, setLoading] = useState(() => peekSpeakingPlan(topic) === null)
  const seq = useRef(0)

  useEffect(() => {
    const mine = ++seq.current
    if (peekSpeakingPlan(topic)) {
      setResult(peekSpeakingPlan(topic) ?? null)
      setLoading(false)
      return
    }
    setLoading(true)
    let cancelled = false
    void getSpeakingPlan(topic).then((next) => {
      if (cancelled || mine !== seq.current) return
      setResult(next)
      setLoading(false)
    })
    return () => {
      cancelled = true
    }
  }, [topic])

  if (loading) {
    return (
      <div className="flex items-center gap-2 py-6 spk-body">
        <Loader2 size={16} className="spk-spin text-[#2563eb]" />
        Analysing this question…
      </div>
    )
  }

  if (!result) return null

  const isAi = result.source === 'ai'

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-center gap-2">
        {isAi ? (
          <span className="spk-chip spk-chip-blue">
            <Sparkles size={12} />
            Generated by the AI coach
          </span>
        ) : (
          <span className="spk-chip spk-chip-amber spk-chip-wrap">
            <AlertTriangle size={12} />
            Local template — not written by a model
          </span>
        )}
        <span className="spk-chip spk-chip-slate capitalize">
          {result.analysis.taskType.replace('_', ' ')}
        </span>
      </div>

      {result.source === 'template' && result.fallbackReason && (
        <p className="spk-note spk-note-warn">
          <AlertTriangle size={15} className="mt-0.5 shrink-0" />
          <span>
            {result.fallbackReason} This is the built-in template, not an AI analysis.
          </span>
        </p>
      )}

      <div>
        <p className="spk-label mb-1.5">Core question</p>
        <p className="spk-body">{result.analysis.coreQuestion}</p>
      </div>

      <div className="spk-arg-wrap">
        <div className="spk-arg-grid">
          {result.arguments.slice(0, 2).map((arg) => (
          <div key={arg.label} className="spk-arg">
            <span className="spk-arg-tag mb-2.5">{arg.label}</span>
            <h4 className="spk-title mb-1.5 !text-[0.98rem]">{arg.title}</h4>
            <p className="spk-body mb-4">{arg.explanation}</p>
            <div className="spk-scenario">
              <span className="spk-scenario-badge mb-3">
                <FlaskConical size={11} />
                Invented practice scenario
              </span>
              <dl className="spk-dl">
                {[
                  ['Situation', arg.scenario.setup],
                  ['Action', arg.scenario.action],
                  ['Result', arg.scenario.result],
                  ['Why it answers the question', arg.scenario.whyItSupports],
                ].map(([label, value]) => (
                  <div key={label} className="spk-dl-row">
                    <dt className="spk-dl-key">{label}</dt>
                    <dd className="spk-dl-val">{value}</dd>
                  </div>
                ))}
              </dl>
            </div>
          </div>
        ))}
        </div>
      </div>

      <div>
        <p className="spk-label mb-2 flex items-center gap-1.5">
          <Languages size={12} />
          Key expressions
        </p>
        <div className="flex flex-wrap gap-2">
          {result.language.keyExpressions.map((e) => (
            <span key={e} className="spk-token spk-token-blue">
              {e}
            </span>
          ))}
        </div>
      </div>

      {result.modelAnswer && (
        <details className="spk-disclosure">
          <summary className="spk-disclosure-head">
            <BookOpen size={15} />
            Full model answer
            <span className="spk-muted ml-auto">optional</span>
            <ChevronDown size={15} className="spk-chevron" />
          </summary>
          <p className="spk-body px-4 pb-4 pt-0">{result.modelAnswer.english}</p>
        </details>
      )}
    </div>
  )
}

type SessionPhase = 'preparation' | 'speaking' | 'review';

const PHASE_STEPS: { id: SessionPhase; label: string }[] = [
  { id: 'preparation', label: 'Preparation' },
  { id: 'speaking', label: 'Speaking' },
  { id: 'review', label: 'Review' },
];

const PREP_OPTIONS = [15, 30, 60];
const SPEAK_OPTIONS = [30, 45, 60];

interface SpeakingArenaProps {
  topic: Topic;
  onBack: () => void;
  /** Optional: the shell can open the coach panel from its own chrome. */
  onShowFramework?: (topic: Topic) => void;
}

export default function SpeakingArena({ topic, onBack }: SpeakingArenaProps) {
  const [phase, setPhase] = useState<SessionPhase>('preparation');
  const [prepTime, setPrepTime] = useState(15);
  const [speakTime, setSpeakTime] = useState(45);
  const [timeLeft, setTimeLeft] = useState(15);
  const [isRunning, setIsRunning] = useState(false);
  const [showHints, setShowHints] = useState(false);
  const [volumeLevel, setVolumeLevel] = useState(0);
  const [recording, setRecording] = useState<RecordingResult | null>(null);
  const [selfRating, setSelfRating] = useState(0);
  const [notes, setNotes] = useState('');
  const [isFav, setIsFav] = useState(() => isFavorite(topic.id));
  const [micError, setMicError] = useState<string | null>(null);
  const [showAnswer, setShowAnswer] = useState(false);
  const [showCoachPanel, setShowCoachPanel] = useState(false);
  const [customSpeak, setCustomSpeak] = useState('');

  const recorderRef = useRef(new RecorderService());
  // Deadline-based timing: immune to interval drift and background-tab throttling.
  const deadlineRef = useRef<number | null>(null);
  const timeLeftRef = useRef(15);
  const prepTimeRef = useRef(15);
  const speakTimeRef = useRef(45);
  const lastBeepRef = useRef<number | null>(null);

  useEffect(() => {
    timeLeftRef.current = timeLeft;
  }, [timeLeft]);

  // Wire recorder callbacks once.
  useEffect(() => {
    const recorder = recorderRef.current;
    recorder.onStateChange = (state) => {
      if (state.error) setMicError(state.error);
    };
    recorder.onVolumeLevel = (level) => setVolumeLevel(level);
    return () => {
      recorder.cancelRecording();
    };
  }, []);

  // Stable transitions — no dependency arrays to get wrong.
  const beginSpeaking = useCallback(() => {
    const duration = speakTimeRef.current;
    setPhase('speaking');
    setTimeLeft(duration);
    deadlineRef.current = Date.now() + duration * 1000;
    lastBeepRef.current = null;
    setIsRunning(true);
    sounds.click();
    recorderRef.current.startRecording().then((ok) => {
      if (ok) sounds.recordingStart();
    });
  }, []);

  const finishSpeaking = useCallback(() => {
    deadlineRef.current = null;
    setIsRunning(false);
    recorderRef.current.stopRecording().then((result) => {
      if (result) {
        sounds.recordingStop();
        setRecording(result);
      }
      setPhase('review');
    });
  }, []);

  const startPreparation = useCallback(() => {
    const duration = prepTimeRef.current;
    sounds.click();
    setPhase('preparation');
    setTimeLeft(duration);
    deadlineRef.current = Date.now() + duration * 1000;
    lastBeepRef.current = null;
    setIsRunning(true);
  }, []);

  // Single ticker driving the whole session.
  useEffect(() => {
    if (!isRunning) return;

    const tick = () => {
      const deadline = deadlineRef.current;
      if (deadline == null) return;

      const remaining = Math.max(0, Math.ceil((deadline - Date.now()) / 1000));
      setTimeLeft(remaining);

      if (remaining > 0 && remaining <= 5 && lastBeepRef.current !== remaining) {
        lastBeepRef.current = remaining;
        sounds.countdownEnd();
      }

      if (remaining === 0) {
        lastBeepRef.current = null;
        if (phase === 'preparation') beginSpeaking();
        else if (phase === 'speaking') finishSpeaking();
      }
    };

    const id = window.setInterval(tick, 200);
    tick();
    return () => window.clearInterval(id);
  }, [isRunning, phase, beginSpeaking, finishSpeaking]);

  const selectPrepTime = (seconds: number) => {
    sounds.click();
    setPrepTime(seconds);
    prepTimeRef.current = seconds;
    if (!isRunning) {
      deadlineRef.current = null;
      setTimeLeft(seconds);
    }
  };

  const selectSpeakTime = (seconds: number) => {
    sounds.click();
    setSpeakTime(seconds);
    speakTimeRef.current = seconds;
    setCustomSpeak('');
    if (!isRunning) {
      deadlineRef.current = null;
      setTimeLeft(seconds);
    }
  };

  const applyCustomSpeak = () => {
    const parsed = Number(customSpeak);
    if (!Number.isFinite(parsed)) return;
    const clamped = Math.min(300, Math.max(10, Math.round(parsed)));
    setSpeakTime(clamped);
    speakTimeRef.current = clamped;
    setCustomSpeak('');
    if (!isRunning) {
      deadlineRef.current = null;
      setTimeLeft(clamped);
    }
  };

  const handlePauseResume = () => {
    if (isRunning) {
      sounds.click();
      deadlineRef.current = null;
      setIsRunning(false);
      recorderRef.current.pauseRecording();
    } else {
      sounds.click();
      deadlineRef.current = Date.now() + timeLeftRef.current * 1000;
      lastBeepRef.current = null;
      setIsRunning(true);
      recorderRef.current.resumeRecording();
    }
  };

  const handleSave = () => {
    sounds.click();
    savePracticeRecord({
      id: Date.now().toString(),
      topicId: topic.id,
      topic,
      practicedAt: Date.now(),
      duration: recording?.duration || speakTime,
      preparationTime: prepTime,
      speakingTime: speakTime,
      selfRating,
      notes,
      hasRecording: !!recording,
    });
    onBack();
  };

  const handleToggleFavorite = () => {
    sounds.click();
    setIsFav(toggleFavorite(topic.id));
  };

  const handleRetry = () => {
    sounds.click();
    deadlineRef.current = null;
    lastBeepRef.current = null;
    setIsRunning(false);
    setPhase('preparation');
    setTimeLeft(prepTimeRef.current);
    setRecording(null);
    setSelfRating(0);
    setNotes('');
    setVolumeLevel(0);
    setShowAnswer(false);
  };

  const categoryName = CATEGORIES.find((c) => c.id === topic.category)?.name || topic.category;
  const phaseIndex = PHASE_STEPS.findIndex((s) => s.id === phase);

  return (
    <div className="spk-scope spk-root">
      {/* Fluid backdrop — fixed, decorative, and never intercepts pointer events. */}
      <div className="spk-backdrop" aria-hidden="true">
        <span className="spk-blob spk-blob-a" />
        <span className="spk-blob spk-blob-b" />
        <span className="spk-blob spk-blob-c" />
        <span className="spk-grid" />
      </div>

      <div className="spk-content">
        <div className="mx-auto w-full max-w-5xl px-4 sm:px-6 pt-24 pb-16">
        {/* Top bar */}
        <div className="mb-6 flex items-center justify-between gap-3">
          <button
            onClick={onBack}
            className="spk-btn"
          >
            <ArrowLeft size={16} />
            Back
          </button>

          <div className="flex items-center gap-2">
            <button
              onClick={handleToggleFavorite}
              aria-pressed={isFav}
              aria-label={isFav ? 'Remove from favorites' : 'Add to favorites'}
              className={`spk-btn spk-btn-icon ${isFav ? 'spk-btn-fav' : ''}`}
            >
              <Heart size={16} fill={isFav ? 'currentColor' : 'none'} />
            </button>
            <button
              onClick={() => setShowCoachPanel(true)}
              className="spk-btn"
            >
              <BookOpen size={16} />
              Speaking Coach
            </button>
          </div>
        </div>

        {/* Phase stepper */}
        <ol className="mb-5 flex items-center gap-2 sm:gap-3" aria-label="Session progress">
          {PHASE_STEPS.map((step, i) => {
            const done = i < phaseIndex;
            const active = i === phaseIndex;
            return (
              <li key={step.id} className="flex min-w-0 flex-1 items-center gap-2 sm:gap-3">
                <span
                  className={`spk-step ${done ? 'spk-step-done' : active ? 'spk-step-active' : ''}`}
                />
                <span
                  className={`spk-step-label ${
                    active ? 'spk-step-label-active' : done ? 'spk-step-label-done' : ''
                  }`}
                >
                  {step.label}
                </span>
              </li>
            );
          })}
        </ol>

        {/* Topic card */}
        <div className="spk-card-hero mb-8 p-5 sm:p-7">
          <p className="spk-label mb-2">Current question</p>
          <p className="spk-title mb-4">{topic.question}</p>
          <div className="flex flex-wrap items-center gap-2">
            <span className="spk-chip spk-chip-blue">{categoryName}</span>
            <span className={`spk-chip ${topic.difficulty === 'Easy' ? 'spk-chip-green' : 'spk-chip-amber'}`}>
              {topic.difficulty}
            </span>
            <span className="spk-chip spk-chip-slate">Prep {topic.preparationTime}s</span>
            <span className="spk-chip spk-chip-slate">Speak {topic.speakingTime}s</span>
          </div>
        </div>

        {/* Phase: Preparation */}
        <AnimatePresence mode="wait">
          {phase === 'preparation' && (
            <motion.section
              key="prep"
              initial={{ opacity: 0, y: 12 }}
              animate={{ opacity: 1, y: 0 }}
              exit={{ opacity: 0, y: -12 }}
              transition={{ duration: 0.2 }}
              className="spk-card-solid p-6 text-center sm:p-8"
            >
              <p className="spk-label">Preparation time</p>

              <p className="spk-timer my-6" aria-live="polite">
                {formatTime(isRunning ? timeLeft : prepTime)}
              </p>

              <div className="mx-auto mb-6 w-full max-w-xs">
                <div className="spk-rail">
                  <div
                    className="spk-rail-fill"
                    style={{
                      width: `${Math.max(
                        0,
                        Math.min(100, ((isRunning ? timeLeft : prepTime) / prepTime) * 100),
                      )}%`,
                    }}
                  />
                </div>
              </div>

              <div className="mb-6 flex flex-col items-center gap-3">
                <div className="spk-seg" role="group" aria-label="Preparation time">
                  {PREP_OPTIONS.map((t) => (
                    <button
                      key={t}
                      onClick={() => selectPrepTime(t)}
                      aria-pressed={prepTime === t}
                      className="spk-seg-item"
                    >
                      {t}s
                    </button>
                  ))}
                </div>

                <button
                  onClick={() => setShowHints((v) => !v)}
                  aria-expanded={showHints}
                  className="spk-btn spk-btn-sm"
                >
                  <Lightbulb size={15} />
                  {showHints ? 'Hide hints' : 'Show hints'}
                </button>
              </div>

              {showHints && (
                <motion.div
                  initial={{ opacity: 0, height: 0 }}
                  animate={{ opacity: 1, height: 'auto' }}
                  className="overflow-hidden"
                >
                  <div className="spk-note spk-note-info mx-auto mt-1 max-w-lg text-left">
                    <Lightbulb size={16} className="mt-0.5 shrink-0" />
                    <div>
                      <p className="mb-1.5 font-semibold">Quick tips</p>
                      <ul className="list-disc space-y-1 pl-4">
                        <li>State your main point clearly in the first sentence</li>
                        <li>Use two reasons, each with one concrete example</li>
                        <li>Reserve the last few seconds for a short conclusion</li>
                      </ul>
                    </div>
                  </div>
                </motion.div>
              )}

              <div className="mt-7 flex flex-col items-center gap-3">
                {!isRunning && (
                  <button onClick={startPreparation} className="spk-btn spk-btn-primary spk-btn-lg w-full max-w-xs">
                    <Play size={18} />
                    Start Preparation
                  </button>
                )}

                {isRunning && (
                  <button onClick={beginSpeaking} className="spk-btn">
                    <SkipForward size={16} />
                    Start speaking now
                  </button>
                )}
              </div>
            </motion.section>
          )}

          {/* Phase: Speaking */}
          {phase === 'speaking' && (
            <motion.section
              key="speak"
              initial={{ opacity: 0, y: 12 }}
              animate={{ opacity: 1, y: 0 }}
              exit={{ opacity: 0, y: -12 }}
              transition={{ duration: 0.2 }}
              className="spk-card-solid p-6 text-center sm:p-8"
            >
              <div className="mb-2 flex items-center justify-center gap-2">
                <span className="spk-dot spk-dot-live" />
                <p className="spk-label">Speaking</p>
              </div>

              <p className="spk-timer my-6" aria-live="polite">
                {formatTime(timeLeft)}
              </p>
              <p className="mb-6 spk-muted">{isRunning ? 'remaining' : 'paused'}</p>

              <div className="mx-auto mb-6 w-full max-w-xs">
                <div className="spk-rail">
                  <div
                    className="spk-rail-fill"
                    style={{ width: `${Math.max(0, Math.min(100, (timeLeft / speakTime) * 100))}%` }}
                  />
                </div>
              </div>

              {/* Live level meter driven by real microphone input */}
              <div className="mb-6 flex h-12 items-center justify-center gap-1" aria-hidden="true">
                {Array.from({ length: 24 }).map((_, i) => (
                  <motion.span
                    key={i}
                    animate={{
                      height: volumeLevel > i / 24 ? '100%' : '18%',
                      backgroundColor:
                        volumeLevel > 0.7 ? '#16a34a' : volumeLevel > 0.3 ? '#2563eb' : '#dbe3ef',
                    }}
                    transition={{ duration: 0.08 }}
                    className="w-1.5 rounded-full"
                  />
                ))}
              </div>

              <div className="mb-7 flex min-h-[24px] items-center justify-center gap-2 text-sm font-medium">
                {micError ? (
                  <span className="spk-note spk-note-warn">
                    <AlertCircle size={16} className="mt-0.5 shrink-0" />
                    {micError}
                  </span>
                ) : (
                  <span className={`spk-status ${isRunning ? 'spk-status-live' : 'spk-status-idle'}`}>
                    {isRunning ? <Mic size={16} /> : <MicOff size={16} />}
                    {isRunning ? 'Recording…' : 'Recording paused'}
                  </span>
                )}
              </div>

              <div className="mb-7 flex items-center justify-center gap-4">
                <button
                  onClick={handlePauseResume}
                  aria-label={isRunning ? 'Pause recording' : 'Resume recording'}
                  className="spk-rec"
                >
                  {isRunning ? <Pause size={22} /> : <Play size={22} />}
                </button>
                <button
                  onClick={finishSpeaking}
                  aria-label="Stop recording"
                  className="spk-rec spk-rec-stop"
                >
                  <Square size={20} />
                </button>
              </div>

              <div className="flex flex-wrap items-center justify-center gap-2 border-t border-[rgba(15,23,42,0.08)] pt-5">
                <div className="spk-seg" role="group" aria-label="Speaking time">
                  {SPEAK_OPTIONS.map((t) => (
                    <button
                      key={t}
                      onClick={() => selectSpeakTime(t)}
                      aria-pressed={speakTime === t}
                      className="spk-seg-item spk-seg-item-sm"
                    >
                      {t}s
                    </button>
                  ))}
                </div>
                <div className="flex items-center gap-1.5">
                  <input
                    type="number"
                    min={10}
                    max={300}
                    inputMode="numeric"
                    value={customSpeak}
                    onChange={(e) => setCustomSpeak(e.target.value)}
                    onKeyDown={(e) => {
                      if (e.key === 'Enter') applyCustomSpeak();
                    }}
                    placeholder="Custom"
                    aria-label="Custom speaking time in seconds"
                    className="spk-input spk-input-sm w-24 text-center"
                  />
                  <button onClick={applyCustomSpeak} className="spk-btn spk-btn-sm">
                    Set
                  </button>
                </div>
              </div>
            </motion.section>
          )}

          {/* Phase: Review */}
          {phase === 'review' && (
            <motion.section
              key="review"
              initial={{ opacity: 0, y: 12 }}
              animate={{ opacity: 1, y: 0 }}
              exit={{ opacity: 0, y: -12 }}
              transition={{ duration: 0.2 }}
            >
              <div className="spk-card-solid mb-6 p-5 sm:p-6">
                <p className="spk-label mb-4">Session review</p>

                <div className="mb-5 flex items-center gap-5">
                  <div>
                    <p className="spk-title tabular-nums">
                      {recording ? formatTime(recording.duration) : '—'}
                    </p>
                    <p className="mt-0.5 spk-muted">Actual</p>
                  </div>
                  <span className="h-8 w-px bg-[rgba(15,23,42,0.1)]" />
                  <div>
                    <p className="spk-title tabular-nums">{formatTime(speakTime)}</p>
                    <p className="mt-0.5 spk-muted">Target</p>
                  </div>
                </div>

                {recording && (
                  <div className="mb-5">
                    <p className="spk-muted mb-2">Recording</p>
                    <audio controls src={recording.url} className="spk-audio" />
                  </div>
                )}

                <div className="mb-5">
                  <p className="spk-muted mb-2">Self rating</p>
                  <div className="flex gap-2">
                    {[1, 2, 3, 4, 5].map((n) => (
                      <button
                        key={n}
                        onClick={() => setSelfRating(n)}
                        aria-pressed={selfRating === n}
                        className="spk-btn spk-rate"
                        data-on={selfRating >= n ? 'true' : 'false'}
                      >
                        {n}
                      </button>
                    ))}
                  </div>
                </div>

                <div>
                  <p className="spk-muted mb-2">Practice notes</p>
                  <textarea
                    value={notes}
                    onChange={(e) => setNotes(e.target.value)}
                    placeholder="What went well? What could be improved?"
                    rows={3}
                    className="spk-input resize-none"
                  />
                </div>
              </div>

              <div className="flex flex-col gap-3 sm:flex-row">
                <button onClick={handleSave} className="spk-btn spk-btn-primary sm:flex-1">
                  <Check size={18} />
                  Save Session
                </button>
                <button onClick={handleRetry} className="spk-btn">
                  <RotateCcw size={18} />
                  Try Again
                </button>
              </div>

              <div className="mt-6">
                <button
                  onClick={() => setShowAnswer((v) => !v)}
                  aria-expanded={showAnswer}
                  className="spk-btn"
                >
                  <BookOpen size={16} />
                  {showAnswer ? 'Hide' : 'Show'} Speaking Coach
                  <ChevronDown
                    size={16}
                    className={`spk-chevron ${showAnswer ? 'spk-chevron-open' : ''}`}
                  />
                </button>

                {showAnswer && (
                  <motion.div
                    initial={{ opacity: 0, height: 0 }}
                    animate={{ opacity: 1, height: 'auto' }}
                    className="overflow-hidden"
                  >
                    <div className="spk-card-solid mt-4 p-5 sm:p-6">
                      <CoachSummary topic={topic} />
                    </div>
                  </motion.div>
                )}
              </div>
            </motion.section>
          )}
        </AnimatePresence>

        <AnimatePresence>
          {showCoachPanel && (
            <AnswerFrameworkView topic={topic} onClose={() => setShowCoachPanel(false)} />
          )}
        </AnimatePresence>
        </div>
      </div>
    </div>
  );
}
